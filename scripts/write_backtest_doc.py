"""
Writes docs/backtest.md from the backtest numbers train_pipeline.py already
records in outputs/forecasts.csv. Regenerated by the weekly retrain so it
never drifts from what the dashboard shows.

Usage:
    python scripts/write_backtest_doc.py
"""
import os
from datetime import date

import pandas as pd

ROOT = os.path.join(os.path.dirname(__file__), "..")
SRC = os.path.join(ROOT, "outputs", "forecasts.csv")
OUT = os.path.join(ROOT, "docs", "backtest.md")


def run():
    d = pd.read_csv(SRC)
    model_rmse = d["rmse_pct"] * d["current_price"]
    d["naive_err_pct"] = d["naive_rmse"] / d["current_price"]
    # Skill score: 1 - model error / no-change error. >0 means the model adds
    # something over assuming today's price holds; <=0 means it doesn't.
    d["skill"] = 1 - model_rmse / d["naive_rmse"]
    beats = d["beat_naive"].astype(str) == "True"

    lines = [
        "# Backtest summary",
        "",
        f"Generated {date.today()} from `outputs/forecasts.csv` by `scripts/write_backtest_doc.py`.",
        "",
        f"**{beats.sum()} of {len(d)} commodities** have a model that beat a simple "
        "\"price stays the same\" forecast in backtesting. Commodities that don't are "
        "capped at a YELLOW watch signal on the dashboard and can never trigger a RED buy alert.",
        "",
        "## Method",
        "",
        "- Each model (Baseline linear, SARIMA, LSTM) is fit walk-forward on 3 historical "
        "windows and scored on data it never saw (no lookahead). The best model's average "
        "RMSE is the **typical error** shown on each card.",
        "- The **no-change baseline** forecasts that today's price holds; its RMSE is scored "
        "on the final holdout window. Caveat: that is one window vs. the model's three, so "
        "the comparison is close but not perfectly like-for-like.",
        "- **Skill** = 1 - model RMSE / no-change RMSE. Positive = better than no-change.",
        "- **Not yet available:** MAE, directional accuracy, and calibration of stated ranges "
        "on *real* out-of-sample outcomes. Those come from `src/models/track_record.py`, which "
        "scores every logged forecast once it comes due (first ones due 2026-11-06).",
        "",
        "## Per commodity",
        "",
        "| Commodity | Source | Horizon | Typical error | No-change error | Skill | Beats no-change |",
        "|---|---|---|---|---|---|---|",
    ]
    for _, r in d.sort_values("skill", ascending=False).iterrows():
        skill = f"{r['skill']:+.2f}" if pd.notna(r["skill"]) else "n/a"
        naive = f"±{r['naive_err_pct']*100:.1f}%" if pd.notna(r["naive_err_pct"]) else "n/a"
        err = f"±{r['rmse_pct']*100:.1f}%" if pd.notna(r["rmse_pct"]) else "n/a"
        lines.append(f"| {r['commodity']} | {r['source']} | {r['horizon_steps']} {r['horizon_unit']} "
                     f"| {err} | {naive} | {skill} | {'Yes' if str(r['beat_naive']) == 'True' else 'No'} |")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {OUT} ({beats.sum()}/{len(d)} beat no-change)")


if __name__ == "__main__":
    run()
